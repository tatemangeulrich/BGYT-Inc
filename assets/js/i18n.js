class I18nManager {
  constructor() {
    this.currentLang = localStorage.getItem("bgyt_lang") || "fr";
    if (!["fr", "en", "nl"].includes(this.currentLang)) {
      this.currentLang = "fr";
    }
  }

  init() {
    this.setLanguage(this.currentLang, false);
    this.bindEvents();
  }

  setLanguage(lang, persist = true) {
    if (!BGYT_TRANSLATIONS[lang]) return;
    this.currentLang = lang;
    if (persist) {
      localStorage.setItem("bgyt_lang", lang);
    }

    document.documentElement.lang = lang;
    this.updateDOM();

    // Update active state in UI selectors
    document.querySelectorAll("[data-lang-btn]").forEach(btn => {
      const targetLang = btn.getAttribute("data-lang-btn");
      if (targetLang === lang) {
        btn.classList.add("bg-primary-container", "text-on-primary", "font-bold");
        btn.classList.remove("text-on-surface-variant");
      } else {
        btn.classList.remove("bg-primary-container", "text-on-primary", "font-bold");
        btn.classList.add("text-on-surface-variant");
      }
    });

    window.dispatchEvent(new CustomEvent("bgyt_lang_changed", { detail: { lang } }));
  }

  t(key, fallback = "") {
    const dict = BGYT_TRANSLATIONS[this.currentLang] || BGYT_TRANSLATIONS.fr;
    return dict[key] || BGYT_TRANSLATIONS.fr[key] || fallback || key;
  }

  updateDOM() {
    // Translate text content
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      const translation = this.t(key);
      if (translation) {
        el.textContent = translation;
      }
    });

    // Translate placeholders
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      const key = el.getAttribute("data-i18n-placeholder");
      const translation = this.t(key);
      if (translation) {
        el.setAttribute("placeholder", translation);
      }
    });

    // Translate titles / tooltips
    document.querySelectorAll("[data-i18n-title]").forEach(el => {
      const key = el.getAttribute("data-i18n-title");
      const translation = this.t(key);
      if (translation) {
        el.setAttribute("title", translation);
      }
    });
  }

  bindEvents() {
    document.querySelectorAll("[data-lang-btn]").forEach(btn => {
      btn.addEventListener("click", (e) => {
        e.preventDefault();
        const lang = btn.getAttribute("data-lang-btn");
        this.setLanguage(lang);
      });
    });
  }
}

// Global instance
window.bgytI18n = new I18nManager();
document.addEventListener("DOMContentLoaded", () => {
  window.bgytI18n.init();
});
